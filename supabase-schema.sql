-- Haven Health Clinic demo: minimal appointment-request table.
-- Run this in Supabase SQL Editor only after reviewing your privacy/legal requirements.
-- This table intentionally has no public SELECT policy: website visitors can submit
-- a request, but they cannot read appointment requests from the public website.

create table if not exists public.appointments (
  id bigint generated by default as identity primary key,
  full_name text not null check (char_length(full_name) between 2 and 80),
  phone text not null check (char_length(phone) between 10 and 25),
  email text,
  service text not null,
  preferred_date date not null,
  preferred_time text,
  notes text check (notes is null or char_length(notes) <= 500),
  created_at timestamptz not null default now()
);

alter table public.appointments enable row level security;

grant insert on table public.appointments to anon, authenticated;

drop policy if exists "Allow public appointment requests" on public.appointments;
create policy "Allow public appointment requests"
on public.appointments
for insert
to anon, authenticated
with check (
  char_length(full_name) between 2 and 80
  and char_length(phone) between 10 and 25
  and char_length(service) > 0
  and preferred_date >= current_date
);

-- Do not add a public SELECT policy. Review rate limiting, spam protection,
-- retention, consent wording, and applicable privacy rules before real-world use.
